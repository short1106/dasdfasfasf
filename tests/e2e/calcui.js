const { _electron } = require('playwright');
const path = require('path');
const SP = require('path').join(__dirname, '..', 'out'), APP = require('path').resolve(__dirname, '..', '..');
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const app = await _electron.launch({ executablePath: APP + '/node_modules/electron/dist/electron', args: [APP, '--no-sandbox', '--enable-unsafe-swiftshader'] });
  const page = await app.firstWindow();
  const errs = []; page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); }); page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
  await wait(1500); await page.keyboard.press('Escape'); await wait(3000);
  const R = {};
  await page.click('#btnCalc'); await wait(900);
  R.open = await page.evaluate(() => document.getElementById('calc').classList.toString());
  for (const k of ['1','2','*','(','3','+','4',')']) await page.keyboard.press(k);
  await wait(200);
  R.live = await page.textContent('#calcOut');
  await page.keyboard.press('Enter'); await wait(500);
  R.eq = await page.textContent('#calcOut');
  R.hist = await page.textContent('#calcHist');
  await page.screenshot({ path: path.join(SP, 'shots5/calc-panel.png') });
  await page.keyboard.press('Escape'); await wait(600);
  await page.keyboard.press('Control+Shift+R'); await wait(800);
  R.shortcut = await page.evaluate(() => document.getElementById('calc').classList.toString());
  await page.keyboard.press('Escape'); await wait(600);
  await page.keyboard.press('Control+L'); await page.keyboard.type('200*15%'); await wait(700);
  R.sugg = await page.evaluate(() => [...document.querySelectorAll('#suggest *')].map(e => e.textContent).filter(Boolean).slice(0, 3).join(' | '));
  await page.screenshot({ path: path.join(SP, 'shots5/calc-omni.png') });
  await page.keyboard.press('Enter'); await wait(800);
  R.toast = await page.evaluate(() => document.body.innerText.match(/kopiert[^\n]*/i)?.[0]);
  console.log(JSON.stringify(R, null, 1));
  console.log('ERRORS:', errs.length ? errs.join('\n') : 'keine');
  await app.close();
})();
